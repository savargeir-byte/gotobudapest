import { defineArrayMember, defineField, defineType } from "sanity";
import {
  editorialOrderings,
  faqsField,
  galleryField,
  groups,
  heroImageField,
  highlightsField,
  orderField,
  publishedAtField,
  refArray,
  seoField,
  slugField,
  sourcesField,
} from "./shared";

export const neighbourhood = defineType({
  name: "neighbourhood",
  title: "Neighbourhood",
  type: "document",
  groups,
  fields: [
    defineField({
      name: "title",
      title: "Title",
      type: "string",
      group: "content",
      validation: (rule) => rule.required(),
    }),
    slugField("title"),
    defineField({
      name: "eyebrow",
      title: "Eyebrow",
      type: "string",
      group: "content",
    }),
    defineField({
      name: "summary",
      title: "Summary",
      type: "text",
      rows: 2,
      group: "content",
      validation: (rule) => rule.required(),
    }),
    heroImageField,
    galleryField,
    defineField({
      name: "intro",
      title: "Introduction",
      type: "text",
      rows: 5,
      group: "content",
      validation: (rule) => rule.required(),
    }),
    highlightsField,
    defineField({
      name: "sections",
      title: "Sections",
      type: "array",
      group: "content",
      of: [defineArrayMember({ type: "topicSection" })],
      validation: (rule) => rule.required().min(1),
    }),
    faqsField,
    defineField({
      name: "placesHeading",
      title: "Places heading",
      type: "string",
      group: "content",
    }),
    defineField({
      name: "placesIntro",
      title: "Places introduction",
      type: "text",
      rows: 2,
      group: "content",
    }),
    refArray("places", "Places (in display order)", "attraction", { max: 30 }),
    refArray("guides", "Related guides", "guide", { max: 6 }),
    defineField({
      name: "region",
      title: "Region / district",
      type: "reference",
      group: "relations",
      to: [{ type: "region" }],
    }),
    sourcesField,
    publishedAtField,
    orderField,
    seoField,
  ],
  preview: {
    select: { title: "title", subtitle: "summary", media: "heroImage" },
  },
  orderings: editorialOrderings,
});

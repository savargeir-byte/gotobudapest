import { defineArrayMember, defineField, defineType } from "sanity";
import {
  editorialOrderings,
  faqsField,
  galleryField,
  groups,
  heroImageField,
  highlightsField,
  orderField,
  publishedAtField,
  refArray,
  seoField,
  slugField,
  sourcesField,
} from "./shared";

export const guide = defineType({
  name: "guide",
  title: "Travel guide",
  type: "document",
  groups,
  fields: [
    defineField({
      name: "title",
      title: "Title",
      type: "string",
      group: "content",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "shortTitle",
      title: "Short title (cards)",
      type: "string",
      group: "content",
      validation: (rule) => rule.required(),
    }),
    slugField("title"),
    defineField({
      name: "category",
      title: "Category",
      type: "reference",
      group: "content",
      to: [{ type: "category" }],
      options: { filter: 'kind == "guide"' },
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "description",
      title: "Description",
      type: "text",
      rows: 3,
      group: "content",
      validation: (rule) => rule.required(),
    }),
    heroImageField,
    galleryField,
    defineField({
      name: "intro",
      title: "Introduction",
      type: "text",
      rows: 5,
      group: "content",
      validation: (rule) => rule.required(),
    }),
    highlightsField,
    defineField({
      name: "sections",
      title: "Sections",
      type: "array",
      group: "content",
      of: [defineArrayMember({ type: "guideSection" })],
      validation: (rule) => rule.required().min(1),
    }),
    faqsField,
    sourcesField,
    defineField({
      name: "updated",
      title: "Last reviewed",
      type: "date",
      group: "content",
      validation: (rule) => rule.required(),
    }),
    publishedAtField,
    orderField,
    seoField,
    refArray("relatedGuides", "Related guides", "guide", { max: 6 }),
    refArray("relatedAttractions", "Related attractions", "attraction", {
      max: 20,
    }),
  ],
  preview: {
    select: { title: "title", subtitle: "category.title", media: "heroImage" },
  },
  orderings: editorialOrderings,
});
